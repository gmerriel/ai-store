"""
experiment_tracker.py — Creative Experiment Tracker for Valher Media.

Every concept and hook generated by Skill 2 is auto-logged here.
Results are updated manually (via this CLI) or by Atlas after reviewing weekly data.
Before each Skill 2 run, past experiments are pulled and fed to GPT-4o
so it never repeats a dead angle and always builds on proven patterns.

COMMANDS:

  List experiments for a funnel:
    python3 experiment_tracker.py list --account profitable_tradie --funnel labour_cost_calc

  Update an experiment outcome:
    python3 experiment_tracker.py update --id <id> --status WINNER --cpl 2.40 --spend 320 --lesson "Exact hours framing outperforms family sacrifice"

  Weekly report (all accounts, all funnels):
    python3 experiment_tracker.py report

  Summary of patterns learned (feed to brief):
    python3 experiment_tracker.py patterns --account profitable_tradie --funnel labour_cost_calc
"""

import argparse
import json
import os
import sys
import uuid
from datetime import datetime
from typing import List, Dict, Any, Optional

from creative_config import get_supabase_client, ACCOUNTS

# ─── STATUS VALUES ────────────────────────────────────────────────────────────
VALID_STATUSES = {"ACTIVE", "WINNER", "INCONCLUSIVE", "KILLED", "NOT_LAUNCHED"}

STATUS_EMOJI = {
    "ACTIVE":       "🔵",
    "WINNER":       "✅",
    "INCONCLUSIVE": "⚪",
    "KILLED":       "❌",
    "NOT_LAUNCHED": "⏭️",
}

ANGLE_EMOJIS = {
    "specific_numbers":  "🔢",
    "pain":              "💔",
    "proof":             "📊",
    "story":             "📖",
    "curiosity":         "🤔",
    "mechanism":         "⚙️",
    "comparison":        "⚖️",
    "pattern_interrupt": "⚡",
}

# ─── AUTO-LOG (called by Skill 2) ─────────────────────────────────────────────

def auto_classify_angle(hook_text: str, hook_type: str) -> str:
    """
    Classify a hook's angle type from its text.
    Used at log time so future reports can group by angle.
    """
    text = hook_text.lower()

    # Specific numbers / data
    import re
    if re.search(r'\d+[\s,]*(?:days?|hours?|weeks?|years?|%|minutes?|seconds?|\$)', text):
        return "specific_numbers"

    # Pain / struggle
    pain_words = ["struggling", "broke", "losing", "tired", "frustrat", "drain", "overwhelm",
                  "can't", "cannot", "stop", "barely", "still not", "wrong", "waste"]
    if any(w in text for w in pain_words):
        return "pain"

    # Social proof / results
    proof_words = ["result", "tripled", "doubled", "grew", "increased", "proof", "case study",
                   "transform", "went from", "used to", "now earn", "saved", "clients"]
    if any(w in text for w in proof_words):
        return "proof"

    # Story / personal
    story_words = ["i was", "i used to", "my wife", "my family", "i remember", "back when",
                   "last year", "story", "dad", "mum", "kids", "son", "daughter"]
    if any(w in text for w in story_words):
        return "story"

    # Mechanism / how-it-works
    mechanism_words = ["here's how", "the reason", "why your", "the secret", "the formula",
                       "this is why", "the system", "the method", "calculator", "tool", "framework"]
    if any(w in text for w in mechanism_words):
        return "mechanism"

    # Comparison
    comparison_words = ["vs", "versus", "compare", "difference between", "instead of",
                        "not just", "unlike", "other", "most ", "average"]
    if any(w in text for w in comparison_words):
        return "comparison"

    # Pattern interrupt (question / bold claim)
    if text.strip().endswith("?") or text.strip().startswith("what if") or text.strip().startswith("stop "):
        return "curiosity"

    return "curiosity"  # default


def auto_generate_hypothesis(angle_type: str, hook_type: str, funnel_name: str, image_format: Optional[str] = None) -> str:
    """
    Generate a concise 1-line hypothesis for the experiment log.
    """
    offer = funnel_name.replace("_", " ")
    format_note = f" via {image_format.replace('-', ' ')}" if image_format else ""
    kind = "Continuer" if hook_type == "continuer" else "Explorer"
    angle = angle_type.replace("_", " ")
    return f"{kind} — {angle} angle{format_note} for {offer}"


def log_experiments_from_concepts(
    account_key: str,
    funnel_name: str,
    week_start: str,
    concepts: List[Dict[str, Any]],
    image_format: Optional[str] = None,
) -> int:
    """
    Auto-log all hooks from a Skill 2 run as ACTIVE experiments.
    Called at the end of skill2_ad_copy_writer.run().
    Returns number of rows inserted.
    """
    sb = get_supabase_client()
    account = ACCOUNTS[account_key]
    rows_inserted = 0

    for c in concepts:
        concept_id = c.get("concept_id", "")
        concept_name = c.get("concept_name", "")

        all_hooks = []
        for body_ref in ["A", "B"]:
            hooks = c.get(f"hooks_{body_ref.lower()}", [])
            if isinstance(hooks, str):
                hooks = json.loads(hooks)
            for h in hooks:
                all_hooks.append((body_ref, h))

        for body_ref, h in all_hooks:
            hook_text = h.get("text", "")
            hook_type = h.get("type", "explorer")
            hook_index = h.get("index", 0)

            angle_type = auto_classify_angle(hook_text, hook_type)
            hypothesis = auto_generate_hypothesis(angle_type, hook_type, funnel_name, image_format)

            exp_id = str(uuid.uuid5(
                uuid.NAMESPACE_DNS,
                f"{account_key}|{funnel_name}|{week_start}|{concept_id}|{body_ref}|{hook_index}"
            ))

            row = {
                "id":           exp_id,
                "account_id":   account["account_id"],
                "account_slug": account_key,
                "funnel_name":  funnel_name,
                "week_launched": week_start,
                "concept_id":   concept_id,
                "concept_name": concept_name,
                "hook_index":   hook_index,
                "hook_type":    hook_type,
                "hook_text":    hook_text,
                "angle_type":   angle_type,
                "image_format": image_format,
                "hypothesis":   hypothesis,
                "status":       "ACTIVE",
            }

            try:
                sb.table("ad_experiments").upsert(row, on_conflict="id").execute()
                rows_inserted += 1
            except Exception as e:
                print(f"  [WARN] Failed to log experiment {exp_id}: {e}")

    return rows_inserted


# ─── PAST EXPERIMENTS QUERY (called by Skill 2 before generating) ─────────────

def get_past_experiments_for_prompt(
    account_key: str,
    funnel_name: str,
    limit_weeks: int = 12,
) -> str:
    """
    Return a formatted string of past experiments for injection into the Skill 2 prompt.
    Grouped by status: WINNERS first, then KILLED/INCONCLUSIVE, omit ACTIVE (still running).
    """
    sb = get_supabase_client()

    try:
        resp = (
            sb.table("ad_experiments")
            .select("*")
            .eq("account_slug", account_key)
            .eq("funnel_name", funnel_name)
            .in_("status", ["WINNER", "KILLED", "INCONCLUSIVE"])
            .order("week_launched", desc=True)
            .limit(limit_weeks * 20)  # ~20 experiments per week
            .execute()
        )
        experiments = resp.data or []
    except Exception:
        return ""  # Fail silently — experiment log is supplementary

    if not experiments:
        return ""

    winners = [e for e in experiments if e["status"] == "WINNER"]
    killed = [e for e in experiments if e["status"] == "KILLED"]
    inconclusive = [e for e in experiments if e["status"] == "INCONCLUSIVE"]

    lines = ["─── CREATIVE EXPERIMENT HISTORY (read before generating) ───────────────────",
             "",
             "This is institutional memory. Use it to avoid repeating failed angles and",
             "double down on proven patterns. More recent = more relevant.",
             ""]

    if winners:
        lines.append("✅ PROVEN WINNERS (these angles beat the CPL threshold):")
        for e in winners[:8]:
            cpl = f" — CPL ${e['outcome_cpl']:.2f}" if e.get("outcome_cpl") else ""
            vs = f" ({e['vs_funnel_avg']} avg)" if e.get("vs_funnel_avg") else ""
            lesson = f" | Lesson: {e['lesson']}" if e.get("lesson") else ""
            lines.append(f"  • [{e['week_launched']}] {e['hypothesis']}{cpl}{vs}{lesson}")
        lines.append("")

    if killed:
        lines.append("❌ KILLED — DO NOT REPEAT THESE ANGLES:")
        for e in killed[:8]:
            cpl = f" — CPL ${e['outcome_cpl']:.2f}" if e.get("outcome_cpl") else ""
            vs = f" ({e['vs_funnel_avg']} avg)" if e.get("vs_funnel_avg") else ""
            lesson = f" | Why: {e['lesson']}" if e.get("lesson") else ""
            lines.append(f"  • [{e['week_launched']}] {e['hypothesis']}{cpl}{vs}{lesson}")
        lines.append("")

    if inconclusive:
        lines.append("⚪ INCONCLUSIVE (insufficient spend — can retest if different angle):")
        for e in inconclusive[:4]:
            spend = f" — only ${e['outcome_spend']:.0f} spend" if e.get("outcome_spend") else ""
            lines.append(f"  • [{e['week_launched']}] {e['hypothesis']}{spend}")
        lines.append("")

    # Angle frequency analysis — what's been over-tested
    from collections import Counter
    all_angles = Counter(e["angle_type"] for e in experiments)
    killed_angles = Counter(e["angle_type"] for e in killed)
    winner_angles = Counter(e["angle_type"] for e in winners)

    lines.append("📊 ANGLE PATTERN SUMMARY:")
    for angle, count in all_angles.most_common():
        w = winner_angles.get(angle, 0)
        k = killed_angles.get(angle, 0)
        emoji = ANGLE_EMOJIS.get(angle, "•")
        lines.append(f"  {emoji} {angle}: {count} tested → {w} winners, {k} killed")
    lines.append("")

    # Untested angles — suggest these
    all_angle_types = set(ANGLE_EMOJIS.keys())
    untested = all_angle_types - set(all_angles.keys())
    if untested:
        lines.append(f"🔍 UNTESTED ANGLES (worth exploring): {', '.join(sorted(untested))}")
        lines.append("")

    lines.append("─────────────────────────────────────────────────────────────────────────")
    return "\n".join(lines)


# ─── CLI COMMANDS ─────────────────────────────────────────────────────────────

def cmd_list(args):
    sb = get_supabase_client()
    q = sb.table("ad_experiments").select("*")
    if args.account:
        q = q.eq("account_slug", args.account)
    if args.funnel:
        q = q.eq("funnel_name", args.funnel)
    if args.status:
        q = q.eq("status", args.status.upper())
    q = q.order("week_launched", desc=True).limit(args.limit or 50)
    rows = q.execute().data or []

    if not rows:
        print("No experiments found.")
        return

    current_funnel = None
    for e in rows:
        funnel_key = f"{e['account_slug']} / {e['funnel_name']}"
        if funnel_key != current_funnel:
            print(f"\n── {funnel_key} ──")
            current_funnel = funnel_key

        emoji = STATUS_EMOJI.get(e["status"], "•")
        cpl = f"CPL ${e['outcome_cpl']:.2f}" if e.get("outcome_cpl") else "no CPL yet"
        spend = f"${e['outcome_spend']:.0f} spend" if e.get("outcome_spend") else ""
        lesson = f"\n     └ {e['lesson']}" if e.get("lesson") else ""
        print(f"  {emoji} [{e['week_launched']}] H{e['hook_index']} [{e['hook_type'][:4]}] "
              f"{e['hypothesis']} | {cpl} {spend}{lesson}")
        print(f"       \"{e['hook_text'][:80]}{'...' if len(e.get('hook_text','')) > 80 else ''}\"")
        print(f"       ID: {e['id']}")


def cmd_update(args):
    if not args.id:
        print("ERROR: --id required")
        sys.exit(1)
    if args.status and args.status.upper() not in VALID_STATUSES:
        print(f"ERROR: --status must be one of {VALID_STATUSES}")
        sys.exit(1)

    sb = get_supabase_client()
    patch = {"updated_at": datetime.utcnow().isoformat()}

    if args.status:
        patch["status"] = args.status.upper()
    if args.cpl is not None:
        patch["outcome_cpl"] = float(args.cpl)
    if args.spend is not None:
        patch["outcome_spend"] = float(args.spend)
    if args.lesson:
        patch["lesson"] = args.lesson
    if args.vs_avg:
        patch["vs_funnel_avg"] = args.vs_avg
    if args.week_closed:
        patch["week_closed"] = args.week_closed

    resp = sb.table("ad_experiments").update(patch).eq("id", args.id).execute()
    if resp.data:
        e = resp.data[0]
        print(f"✅ Updated: {e['hypothesis']} → {e['status']}")
    else:
        print(f"⚠️  No row found with id={args.id}")


def cmd_report(args):
    sb = get_supabase_client()
    resp = sb.table("ad_experiments").select("*").order("week_launched", desc=True).limit(500).execute()
    rows = resp.data or []

    if not rows:
        print("No experiments recorded yet.")
        return

    from collections import defaultdict, Counter
    by_account = defaultdict(lambda: defaultdict(list))
    for e in rows:
        by_account[e["account_slug"]][e["funnel_name"]].append(e)

    print(f"\n{'='*70}")
    print(f"  CREATIVE EXPERIMENT REPORT — {datetime.now().strftime('%Y-%m-%d')}")
    print(f"{'='*70}")

    for account, funnels in sorted(by_account.items()):
        print(f"\n📦 {account.upper()}")
        for funnel, experiments in sorted(funnels.items()):
            winners   = [e for e in experiments if e["status"] == "WINNER"]
            killed    = [e for e in experiments if e["status"] == "KILLED"]
            active    = [e for e in experiments if e["status"] == "ACTIVE"]
            inconc    = [e for e in experiments if e["status"] == "INCONCLUSIVE"]
            total     = len(experiments)

            print(f"\n  ── {funnel} ({total} total: "
                  f"✅{len(winners)} ❌{len(killed)} 🔵{len(active)} ⚪{len(inconc)})")

            if winners:
                best = min(winners, key=lambda e: e.get("outcome_cpl") or 999)
                print(f"     Best winner: {best['hypothesis']}"
                      + (f" — CPL ${best['outcome_cpl']:.2f}" if best.get("outcome_cpl") else ""))

            angle_wins = Counter(e["angle_type"] for e in winners)
            angle_kills = Counter(e["angle_type"] for e in killed)
            if angle_wins:
                top = angle_wins.most_common(2)
                print(f"     ✅ Top angles: {', '.join(f'{a}({n})' for a,n in top)}")
            if angle_kills:
                dead = angle_kills.most_common(2)
                print(f"     ❌ Dead angles: {', '.join(f'{a}({n})' for a,n in dead)}")

    print(f"\n{'='*70}\n")


def cmd_patterns(args):
    if not args.account or not args.funnel:
        print("ERROR: --account and --funnel required")
        sys.exit(1)
    output = get_past_experiments_for_prompt(args.account, args.funnel)
    print(output if output else "No closed experiments yet for this funnel.")


# ─── MAIN ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Creative Experiment Tracker")
    sub = parser.add_subparsers(dest="command", required=True)

    # list
    p_list = sub.add_parser("list", help="List experiments")
    p_list.add_argument("--account")
    p_list.add_argument("--funnel")
    p_list.add_argument("--status")
    p_list.add_argument("--limit", type=int, default=50)

    # update
    p_upd = sub.add_parser("update", help="Update experiment outcome")
    p_upd.add_argument("--id", required=True)
    p_upd.add_argument("--status", choices=list(VALID_STATUSES))
    p_upd.add_argument("--cpl", type=float)
    p_upd.add_argument("--spend", type=float)
    p_upd.add_argument("--lesson")
    p_upd.add_argument("--vs-avg", dest="vs_avg")
    p_upd.add_argument("--week-closed", dest="week_closed")

    # report
    sub.add_parser("report", help="Full weekly report across all accounts")

    # patterns
    p_pat = sub.add_parser("patterns", help="Show experiment patterns for Skill 2 injection")
    p_pat.add_argument("--account", required=True)
    p_pat.add_argument("--funnel", required=True)

    args = parser.parse_args()

    if args.command == "list":    cmd_list(args)
    elif args.command == "update": cmd_update(args)
    elif args.command == "report": cmd_report(args)
    elif args.command == "patterns": cmd_patterns(args)


if __name__ == "__main__":
    main()
